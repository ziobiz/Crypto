const PRIORITY_CODES = new Set(REMITTANCE_PRIORITY_COUNTRIES.map((c) => c.code));

export const REMITTANCE_OTHER_COUNTRIES: RemittanceCountry[] = OTHER_UNSORTED.filter(
  (c) => !PRIORITY_CODES.has(c.code),
).sort((a, b) => a.name.localeCompare(b.name, 'en'));

const ALLOWED = new Set<string>([
  ...REMITTANCE_PRIORITY_COUNTRIES.map((c) => c.code),
  ...REMITTANCE_OTHER_COUNTRIES.map((c) => c.code),
]);

export function isAllowedRemittanceCountry(raw?: string | null): boolean {
  const code = String(raw || '')
    .trim()
    .toUpperCase();
  return ALLOWED.has(code);
}

/** Limit country becomes the first option. The selected value can still differ. */
export function remittanceCountryGroups(preferredCode?: string | null): {
  priority: RemittanceCountry[];
  others: RemittanceCountry[];
} {
  const pref = String(preferredCode || '')
    .trim()
    .toUpperCase();
  const priority = [...REMITTANCE_PRIORITY_COUNTRIES];
  const idx = priority.findIndex((c) => c.code === pref);
  if (idx > 0) {
    const [hit] = priority.splice(idx, 1);
    priority.unshift(hit);
  }
  return { priority, others: REMITTANCE_OTHER_COUNTRIES };
}
