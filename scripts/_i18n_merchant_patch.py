root = Path("frontend/src/i18n/locale")
for loc, parts in patches.items():
    p = root / f"{loc}.ts"
    text = p.read_text(encoding="utf-8")
    for key, (old, new) in parts.items():
        if old not in text:
            print(f"MISSING {loc} {key}")
            continue
        if key == "role" and "role.CUSTOMER_OPERATOR" in text:
            continue
        if key == "nav_wallets" and "nav.merchantUsers" in text:
            continue
        text = text.replace(old, new, 1)
    p.write_text(text, encoding="utf-8")
    print("updated", loc)
